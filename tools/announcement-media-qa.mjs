import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { build } from 'esbuild';
import sharp from 'sharp';
import { chromium } from 'playwright-core';
import { findChromium } from '../server/browser-runtime.js';
import { AnnouncementInbox } from '../server/announcements.js';

fs.mkdirSync('.data', { recursive: true });
const root = fs.mkdtempSync(path.resolve('.data', 'announcement-qa-'));
const child = spawn(process.execPath, ['auth-server/dev.js'], { windowsHide: true, env: { ...process.env, PORT: '0', AUTH_DEV_STATE_FILE: path.join(root, 'state.json'), KUA_YIPU_ADMIN_USERNAME: 'test', KUA_YIPU_ADMIN_PASSWORD: 'local-test-password' }, stdio: ['ignore', 'pipe', 'pipe'] });
const exited = once(child, 'exit');
let browser;
let adminPage;
try {
  const endpoint = await new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(Error('Preview did not start')), 10000);
    child.once('error', reject);
    child.stdout.on('data', chunk => { const url = String(chunk).match(/http:\/\/127\.0\.0\.1:\d+/)?.[0]; if (url) { clearTimeout(timer); resolve(url); } });
  });
  browser = await chromium.launch({ executablePath: findChromium(), headless: true, args: ['--mute-audio'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  adminPage = page;
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => { if (response.url().includes('announcement-images') && response.status() >= 400) console.error('Image response:', response.status(), new URL(response.url()).pathname); });
  await page.goto(endpoint + '/admin/');
  await page.locator('#adminUser').fill('test'); await page.locator('#adminPass').fill('local-test-password');
  await page.locator('#loginForm button').click();
  await page.locator('#app').waitFor();
  const token = await page.evaluate(() => sessionStorage.getItem('auth-admin-token'));
  async function api(url, data, method = 'POST') {
    const response = await fetch(endpoint + url, { method, headers: { authorization: `Bearer ${token}`, 'content-type': 'application/json' }, ...(data ? { body: JSON.stringify(data) } : {}) });
    assert.ok(response.ok, `${method} ${url}: ${response.status}`); return response.json();
  }
  await page.locator('#newNoticeNav').click();
  await page.locator('#noticeTitle').fill('图文使用指南');
  await page.locator('#noticeKind').selectOption('popup-always');
  await page.locator('#noticeContent').fill('欢迎使用抄得快。\n以下为功能说明图片。');
  const svg = '<svg width="900" height="380"><rect width="900" height="380" fill="#12372d"/><rect x="45" y="45" width="810" height="290" rx="18" fill="#e6f3ed"/><text x="90" y="145" font-size="44" fill="#108362">CHAODEKUAI</text><text x="90" y="225" font-size="30" fill="#173d39">Product collection and publishing</text></svg>';
  const picture = path.join(root, 'guide.png');
  await sharp(Buffer.from(svg)).png().toFile(picture);
  await page.locator('#noticeImageFiles').setInputFiles(picture);
  await page.getByText('图片已上传，保存公告后生效', { exact: true }).waitFor();
  await page.getByLabel('图片说明（可选）').fill('功能说明');
  await page.locator('#addNoticeText').click();
  await page.getByLabel('文字段落 3').fill('需要帮助时请联系管理员。<script>不得执行</script>');
  await page.locator('.notice-block').nth(2).getByRole('button', { name: '上移', exact: true }).click();
  await page.locator('.notice-block').nth(1).getByRole('button', { name: '下移', exact: true }).click();
  await page.locator('#previewNotice').click();
  await page.waitForFunction(() => document.querySelector('#previewContent img')?.naturalWidth > 0);
  assert.deepEqual(await page.locator('#previewContent > *').evaluateAll(nodes => nodes.map(node => node.tagName)), ['P', 'FIGURE', 'P']);
  assert.equal(await page.locator('#previewContent script').count(), 0);
  await page.screenshot({ path: path.join(root, 'admin-preview.png') });
  await page.locator('#previewDialog .close-dialog').click();
  await page.locator('#saveNotice').click();
  await page.locator('#noticeDialog').waitFor({ state: 'hidden' });
  let item = (await api('/api/admin/announcements', null, 'GET')).items[0];
  assert.equal(item.status, 'draft'); assert.equal(item.popup_policy, 'every-login');
  assert.deepEqual(item.blocks.map(block => block.type), ['text', 'image', 'text']);
  assert.equal((await fetch(endpoint + item.blocks[1].src)).status, 404);
  await page.locator('[data-notice]').first().click();
  assert.equal(await page.locator('#noticeKind').inputValue(), 'popup-always');
  assert.equal(await page.locator('#noticeBlocks textarea').count(), 2);
  await page.locator('#noticeStatus').selectOption('published');
  await page.screenshot({ path: path.join(root, 'admin-editor.png') });
  await page.locator('#saveNotice').click();
  await page.locator('#noticeDialog').waitFor({ state: 'hidden' });
  item = (await api('/api/announcements', null, 'GET'))[0];
  const inbox = new AnnouncementInbox(path.join(root, 'client-reads.json'), endpoint, 'qa');
  const bundle = await build({ stdin: { loader: 'jsx', resolveDir: process.cwd(), contents: `
    import React from 'react'; import {createRoot} from 'react-dom/client';
    import {useAnnouncements,AnnouncementPopup,AnnouncementsView} from './src/Announcements.jsx';
    import './src/styles.css';
    function App(){const inbox=useAnnouncements();return <><AnnouncementsView inbox={inbox}/><AnnouncementPopup inbox={inbox}/></>}
    createRoot(document.getElementById('root')).render(<App/>);
  ` }, write: false, bundle: true, format: 'esm', jsx: 'automatic', outdir: 'qa', define: { 'process.env.NODE_ENV': '"production"' } });
  const client = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
  client.on('pageerror', error => errors.push(error.message));
  await client.route('https://fonts.googleapis.com/**', route => route.abort());
  await client.route('**/qa-client*', route => {
    const ext = path.extname(new URL(route.request().url()).pathname);
    if (ext) return route.fulfill({ contentType: ext === '.css' ? 'text/css' : 'text/javascript', body: bundle.outputFiles.find(file => file.path.endsWith(ext)).text });
    return route.fulfill({ contentType: 'text/html', body: '<html><meta charset="UTF-8"><link rel="stylesheet" href="/qa-client.css"><body><div id="root"></div><script type="module" src="/qa-client.js"></script></body></html>' });
  });
  await client.route('**/api/announcements?*', async route => route.fulfill({ json: await inbox.list({ refresh: true }) }));
  await client.route('**/api/announcements/read', async route => { const body = route.request().postDataJSON(); await route.fulfill({ json: inbox.markRead(body.id, body.revision) }); });
  const popup = client.getByRole('dialog', { name: '公告', exact: true });
  await client.goto(endpoint + '/qa-client');
  await popup.waitFor();
  await client.waitForFunction(() => document.querySelector('[role=dialog] img')?.naturalWidth > 0);
  assert.equal(await popup.locator('script').count(), 0);
  await client.screenshot({ path: path.join(root, 'client-popup.png') });
  await popup.getByRole('button', { name: '我已阅读' }).click();
  await popup.waitFor({ state: 'hidden' });
  const refresh = () => Promise.all([client.waitForResponse(response => response.url().includes('/api/announcements?')), client.getByTitle('刷新公告').click()]);
  await refresh(); await refresh();
  assert.equal(await popup.count(), 0, 'polling and refreshing must not repeatedly display an already dismissed popup');
  await client.reload(); await popup.waitFor();
  await popup.getByRole('button', { name: '我已阅读' }).click(); await popup.waitFor({ state: 'hidden' });
  await client.getByRole('button', { name: /图文使用指南/ }).click();
  await client.locator('.announcement-item img').waitFor();
  await client.setViewportSize({ width: 430, height: 900 });
  await client.screenshot({ path: path.join(root, 'client-mobile.png'), fullPage: true });
  assert.ok(await client.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await api(`/api/admin/announcements/${item.id}`, { ...item, popup_policy: 'once' }, 'PATCH');
  await refresh(); await popup.waitFor();
  await popup.getByRole('button', { name: '我已阅读' }).click(); await popup.waitFor({ state: 'hidden' });
  await client.reload(); await client.getByRole('button', { name: /图文使用指南/ }).waitFor();
  assert.equal(await popup.count(), 0, 'once policy must respect stored read receipts on next entry');
  await page.locator('[data-notice]').first().click();
  await page.locator('.notice-block').first().getByRole('button', { name: '删除', exact: true }).click();
  await page.locator('.notice-block').last().getByRole('button', { name: '删除', exact: true }).click();
  await page.locator('#saveNotice').click(); await page.locator('#noticeDialog').waitFor({ state: 'hidden' });
  assert.deepEqual((await api('/api/announcements', null, 'GET'))[0].blocks.map(block => block.type), ['image']);
  await page.locator('[data-notice]').first().click();
  await page.locator('.notice-block').getByRole('button', { name: '删除', exact: true }).click();
  await page.locator('#saveNotice').click();
  await page.getByText('请添加公告文字或图片', { exact: true }).waitFor();
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ ok: true, root, verified: ['upload', 'mixed-order', 'draft-privacy', 'edit', 'preview', 'literal-text', 'image-only', 'empty-rejection', 'client-images', 'every-entry-popup', 'no-repeat-on-refresh', 'once-policy', 'mobile-width'] }));
} catch (error) {
  await adminPage?.screenshot({ path: path.join(root, 'failure.png') });
  console.error(JSON.stringify({ root, preview: await adminPage?.locator('#previewContent').innerHTML(), status: await adminPage?.locator('#noticeError').innerText() })); throw error;
} finally {
  await browser?.close(); child.kill(); await exited;
}
