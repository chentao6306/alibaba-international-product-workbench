import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { once } from 'node:events';

test('authorization service supports filtering, expiration correction, deletion, session isolation and announcements', { timeout: 30000 }, async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'auth-dev-test-'));
  const database = process.env.AUTH_TEST_DATABASE_URL;
  if (database && !/^\/auth_qa_[a-z0-9_]+$/.test(new URL(database).pathname)) throw new Error('Authorization integration tests require an isolated auth_qa_ database');
  const child = spawn(process.execPath, [database ? 'auth-server/index.js' : 'auth-server/dev.js'], { windowsHide: true, env: { ...process.env, PORT: '0', BIND_HOST: '127.0.0.1', ...(database ? { DATABASE_URL: database, PGSSL: 'disable', KUA_YIPU_AUTH_SECRET: 'isolated-auth-test-signing-secret-2026' } : {}), AUTH_DEV_STATE_FILE: path.join(root, 'state.json'), KUA_YIPU_ADMIN_USERNAME: 'test', KUA_YIPU_ADMIN_PASSWORD: 'local-test-password' }, stdio: ['ignore', 'pipe', 'pipe'] });
  const exited = once(child, 'exit');
  let token = '';
  try {
    const url = await new Promise((resolve, reject) => {
      const timer = setTimeout(() => reject(new Error('Preview did not start')), 10000);
      child.once('error', reject);
      child.stdout.on('data', (chunk) => { const match = String(chunk).match(/http:\/\/127\.0\.0\.1:\d+/); if (match) { clearTimeout(timer); resolve(match[0]); } });
    });
    const codes = new Map();
    const api = async (route, body, method = 'POST', credential = token) => {
      if (route === '/api/client/login') body = { activationCode: codes.get(body.username), ...body };
      const response = await fetch(url + route, { method, headers: { 'content-type': 'application/json', authorization: `Bearer ${credential}` }, ...(body ? { body: JSON.stringify(body) } : {}) });
      const data = await response.json();
      if (data.activationCode) codes.set(data.alibaba_account, data.activationCode);
      return { status: response.status, data };
    };
    token = (await api('/api/admin/login', { username: 'test', password: 'local-test-password' })).data.token;
    assert.ok(token);
    assert.equal((await fetch(url + '/admin.js')).status, 200);
    const license = (await api('/api/admin/licenses', { alibabaAccount: 'test-account', days: 1 })).data;
    const a = (await api('/api/client/login', { username: 'test-account', deviceId: 'A' })).data.token;
    const b = (await api('/api/client/login', { username: 'test-account', deviceId: 'B' })).data.token;
    assert.equal((await api('/api/client/heartbeat', {}, 'POST', a)).status, 200);
    assert.equal((await api('/api/client/heartbeat', {}, 'POST', b)).status, 200);
    await api(`/api/admin/licenses/${license.id}`, { action: 'devices', allowMultiDevice: false }, 'PATCH');
    const c = (await api('/api/client/login', { username: 'test-account', deviceId: 'C' })).data.token;
    assert.equal((await api('/api/client/heartbeat', {}, 'POST', a)).status, 403);
    assert.equal((await api('/api/client/heartbeat', {}, 'POST', c)).status, 200);
    const extended = (await api(`/api/admin/licenses/${license.id}`, { action: 'extend', days: 30 }, 'PATCH')).data;
    const reduced = (await api(`/api/admin/licenses/${license.id}`, { action: 'reduce', days: 30 }, 'PATCH')).data;
    assert.equal(new Date(extended.expires_at) - new Date(reduced.expires_at), 30 * 86400000);
    assert.equal(reduced.expires_at, license.expires_at);
    assert.equal((await api(`/api/admin/licenses/${license.id}`, { action: 'reduce', days: -1 }, 'PATCH')).status, 400);
    await api(`/api/admin/licenses/${license.id}`, { action: 'pause' }, 'PATCH');
    assert.equal((await api(`/api/admin/licenses/${license.id}`, { action: 'reduce', days: 1 }, 'PATCH')).data.status, 'paused');
    assert.equal((await api(`/api/admin/licenses/${license.id}`, { action: 'resume' }, 'PATCH')).status, 409);
    await api(`/api/admin/licenses/${license.id}`, { action: 'extend', days: 10 }, 'PATCH');
    const page = (await api('/api/admin/licenses?page=1&pageSize=10&status=active&search=test', null, 'GET')).data;
    assert.equal(page.total, 1); assert.equal(page.items[0].display_status, 'active');
    const expired = (await api('/api/admin/licenses', { alibabaAccount: 'expired-test', days: 1 })).data;
    const oldSession = (await api('/api/client/login', { username: 'expired-test', deviceId: 'D' })).data.token;
    await api(`/api/admin/licenses/${expired.id}`, { action: 'reduce', days: 2 }, 'PATCH');
    assert.equal((await api('/api/client/heartbeat', {}, 'POST', oldSession)).status, 403);
    assert.equal((await api('/api/client/login', { username: 'expired-test', deviceId: 'E' })).status, 403);
    const paused = (await api('/api/admin/licenses', { alibabaAccount: 'paused-test', days: 10 })).data;
    await api(`/api/admin/licenses/${paused.id}`, { action: 'pause' }, 'PATCH');
    assert.equal((await api('/api/admin/licenses?status=expired,paused&search=test', null, 'GET')).data.total, 2);
    assert.equal((await api('/api/admin/licenses?status=expired,paused&activity=24h', null, 'GET')).data.total, 1);
    assert.equal((await api('/api/admin/licenses?status=expired,paused&activity=never&devices=multiple', null, 'GET')).data.total, 1);
    assert.equal((await api('/api/admin/licenses?status=active&devices=single&activity=24h', null, 'GET')).data.total, 1);
    assert.equal((await api('/api/admin/licenses?status=unknown', null, 'GET')).status, 400);
    assert.equal((await api(`/api/admin/licenses/${license.id}`, null, 'DELETE', '')).status, 401);
    assert.equal((await api(`/api/admin/licenses/${license.id}`, null, 'DELETE')).status, 200);
    assert.equal((await api('/api/client/heartbeat', {}, 'POST', c)).status, 403);
    assert.equal((await api('/api/client/login', { username: 'test-account', deviceId: 'A' })).status, 403);
    assert.equal((await api('/api/admin/licenses?search=test-account', null, 'GET')).data.total, 0);
    const deleted = (await api('/api/admin/licenses?status=deleted', null, 'GET')).data;
    assert.equal(deleted.total, 1); assert.equal(deleted.items[0].device_count, 0);
    assert.equal((await api(`/api/admin/licenses/${license.id}`, { action: 'extend', days: 1 }, 'PATCH')).status, 409);
    const replacement = (await api('/api/admin/licenses', { alibabaAccount: 'test-account', days: 10 })).data;
    assert.notEqual(replacement.id, license.id);
    assert.equal((await api('/api/client/heartbeat', {}, 'POST', c)).status, 403);
    assert.equal((await api('/api/client/login', { username: 'test-account', deviceId: 'A' })).status, 200);
    const stats = (await api('/api/admin/stats', null, 'GET')).data;
    assert.equal(stats.deleted, 1); assert.equal(stats.total, 3); assert.equal(stats.active, 1); assert.equal(stats.expired, 1); assert.equal(stats.paused, 1);
    for (let i = 0; i < 12; i += 1) await api('/api/admin/licenses', { alibabaAccount: `paged-${i}`, days: 10 });
    const secondPage = (await api('/api/admin/licenses?search=paged-&page=2&pageSize=10', null, 'GET')).data;
    assert.equal(secondPage.total, 12); assert.equal(secondPage.items.length, 2);
    const draft = (await api('/api/admin/announcements', { title: 'Title', content: 'Body', kind: 'popup', status: 'draft' })).data;
    assert.deepEqual((await api('/api/announcements', null, 'GET')).data, []);
    await api(`/api/admin/announcements/${draft.id}`, { ...draft, status: 'published' }, 'PATCH');
    assert.equal((await api('/api/announcements', null, 'GET')).data[0].revision, 2);
    await api(`/api/admin/announcements/${draft.id}`, { ...draft, status: 'withdrawn' }, 'PATCH');
    assert.deepEqual((await api('/api/announcements', null, 'GET')).data, []);
    await api(`/api/admin/announcements/${draft.id}`, { ...draft, status: 'published' }, 'PATCH');
    assert.equal((await api(`/api/admin/announcements/${draft.id}`, null, 'DELETE', '')).status, 401);
    assert.equal((await api(`/api/admin/announcements/${draft.id}`, null, 'DELETE')).status, 200);
    assert.deepEqual((await api('/api/announcements', null, 'GET')).data, []);
    assert.equal((await api('/api/admin/announcements', null, 'GET')).data.total, 0);
    assert.equal((await api(`/api/admin/announcements/${draft.id}`, { ...draft, status: 'published' }, 'PATCH')).status, 404);
  } finally { child.kill(); await exited; fs.rmSync(root, { recursive: true, force: true }); }
});
